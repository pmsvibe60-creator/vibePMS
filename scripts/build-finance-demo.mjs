import ts from '../sidecar/node_modules/typescript/lib/typescript.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = readFileSync(new URL('../sidecar/src/finance/engine.ts', import.meta.url), 'utf8');
const output = '// Generated by scripts/build-finance-demo.mjs; edit the TypeScript engine.\n' + ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
writeFileSync(new URL('../site/finance-engine.js', import.meta.url), output);
const demo = new URL('../site/finance-demo.js', import.meta.url);
writeFileSync(demo, readFileSync(demo, 'utf8').replace(/\.\/finance-engine\.js(?:\?v=[a-f0-9]+)?/, './finance-engine.js?v=' + createHash('sha256').update(output).digest('hex').slice(0,12)));
